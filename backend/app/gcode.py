"""GRBL-style G-code export for the computed cutting schedule."""
from __future__ import annotations

from .scheduler import ScheduleResult


def _f(v: float, invert_y: bool) -> tuple[float, float]:
    return v[0], (-v[1] if invert_y else v[1])


def render_gcode(
    result: ScheduleResult,
    *,
    project_name: str,
    invert_y: bool = True,
    laser_power: int = 255,
    travel_speed: int = 3000,
    cut_speed: int = 600,
    safe_z: float = 5.0,
    preamble: str = "",
) -> str:
    """Render a schedule to G-code (GRBL M4 dynamic laser power mode)."""
    lines: list[str] = [
        f"; Laser cutting path: {project_name}",
        f"; contours: {len(result.order)}  invalid (skipped): {result.invalid_count}",
        f"; total cut length: {result.total_cut:.2f}  total travel: {result.total_travel:.2f}",
        "; generated by laser-cut scheduler (inside-first, nearest-neighbour)",
        "G21",        # millimetres
        "G90",        # absolute positioning
        "G17",
        "M5",         # laser off
    ]
    if preamble.strip():
        lines.extend(preamble.strip().splitlines())

    home_seen = False
    for seg in result.segments:
        if seg["type"] == "travel":
            frm = _f(seg["from"], invert_y)
            to = _f(seg["to"], invert_y)
            if not home_seen:
                lines.append(f"G0 Z{safe_z:.3f}")
                lines.append(f"G0 X{frm[0]:.3f} Y{frm[1]:.3f}")
                home_seen = True
            lines.append("M5")
            lines.append(
                f"G0 X{to[0]:.3f} Y{to[1]:.3f}  ; travel {seg['length']:.2f}")
        else:
            pts = seg["points"]
            if not pts:
                continue
            start = _f(pts[0], invert_y)
            lines.append(f"G0 X{start[0]:.3f} Y{start[1]:.3f}")
            lines.append(f"M4 S{int(laser_power)}  ; contour {seg['contour_id']}")
            lines.append(f"G1 F{int(cut_speed)}")
            for x, y in pts[1:]:
                x, y = _f((x, y), invert_y)
                lines.append(f"G1 X{x:.3f} Y{y:.3f}")
            lines.append("M5")
            lines.append(f"G0 Z{safe_z:.3f}")

    lines.extend([
        "G1 F" + str(int(travel_speed)),
        "; end of job",
        "M5",
        "$H",  # GRBL homing cycle (safe stop)
    ])
    return "\n".join(lines) + "\n"
